// Generates src/index.ts (viem-friendly `as const` ABIs) and json/*.json (for Envio) from contracts/out.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const OUT = join(import.meta.dirname, "../../contracts/out");
const CONTRACTS = [
  "Plenum", "Mandate", "Governance", "ManagerGateway", "NavOracle", "ConsentRegistry", "PlenumFactory",
  "IAssetAdapter", "ComplianceGate", "MockIdentityProvider", "MockAToken", "MockTBillVault", "MockCreditVault", "MockGold",
];

const lower = (s) => s[0].toLowerCase() + s.slice(1);
let ts = "// Generated by generate.mjs from the Foundry build. Do not edit.\n\n";
mkdirSync(join(import.meta.dirname, "json"), { recursive: true });
for (const name of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(join(OUT, `${name}.sol`, `${name}.json`), "utf8"));
  writeFileSync(join(import.meta.dirname, "json", `${name}.json`), JSON.stringify(abi, null, 2) + "\n");
  ts += `export const ${lower(name)}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
ts += `/** Reason enum order from contracts/src/interfaces/Types.sol (ABI: decoded by ordinal). */
export const REASONS = [
  "OK", "ADAPTER_NOT_ALLOWED", "WEIGHT_OUT_OF_BAND", "LIQUIDITY_FLOOR", "TRADE_TOO_LARGE", "TURNOVER_CAP",
  "NAV_STALE", "COOLDOWN", "PAUSED", "PAYEE_NOT_VERIFIED", "MEMBER_NOT_VERIFIED", "JURISDICTION_BLOCKED", "MEMBER_CAP",
] as const;
export type Reason = (typeof REASONS)[number];

/** Op enum order from Types.sol. */
export const OPS = ["Deposit", "Withdraw", "RequestRedeem", "Claim"] as const;
export type OpName = (typeof OPS)[number];
`;
writeFileSync(join(import.meta.dirname, "src/index.ts"), ts);
console.log(`Generated ${CONTRACTS.length} ABIs`);
