// Copies the ABIs the workflow needs from packages/abis into plenum-nav/abis.ts (the CRE compiler bundles one dir).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = join(import.meta.dirname, "../../packages/abis/json");
const pick = { plenumAbi: "Plenum", mandateAbi: "Mandate", iAssetAdapterAbi: "IAssetAdapter" };
let out = "// Generated by scripts/abis.mjs from packages/abis. Do not edit.\n\n";
for (const [exp, name] of Object.entries(pick)) {
  const abi = JSON.parse(readFileSync(join(src, `${name}.json`), "utf8"));
  out += `export const ${exp} = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync(join(import.meta.dirname, "../plenum-nav/abis.ts"), out);
console.log("plenum-nav/abis.ts written");
