// Writes config.yaml from contracts/deployments/<chainId>.json. Usage: node scripts/config.mjs [10143|31337]
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const chainId = Number(process.argv[2] ?? 10143);
if (chainId !== 10143 && chainId !== 31337) throw new Error("Monad testnet (10143) or local (31337) only");
const d = JSON.parse(readFileSync(join(import.meta.dirname, `../../contracts/deployments/${chainId}.json`), "utf8"));
// The hosted builder only receives this folder, so the ABIs the config uses are copied into ./abis (committed).
const ABI_NAMES = ["PlenumFactory", "Plenum", "ManagerGateway", "Governance", "NavOracle", "ConsentRegistry"];
mkdirSync(join(import.meta.dirname, "../abis"), { recursive: true });
for (const name of ABI_NAMES) {
  copyFileSync(join(import.meta.dirname, `../../packages/abis/json/${name}.json`), join(import.meta.dirname, `../abis/${name}.json`));
}
const abi = (name) => `./abis/${name}.json`;

// INDEXER_SOURCE=rpc indexes straight from the Monad RPC (no HyperSync token needed): Monad caps eth_getLogs at
// 100 blocks and ~15 requests/s, so the block interval is pinned at 100 and errors back off.
const rpcOnly = process.env.INDEXER_SOURCE === "rpc";
const chainSource =
  chainId === 10143 && rpcOnly
    ? `    rpc:
      # Ankr allows ~300 requests per 10 s; Monad Foundation and QuickNode are fallbacks (20 and 15 req/s).
      - url: https://rpc.ankr.com/monad_testnet
        for: sync
        initial_block_interval: 100
        interval_ceiling: 500
        backoff_millis: 1500
        polling_interval: 2000
      - url: https://rpc-testnet.monadinfra.com
        for: fallback
        initial_block_interval: 100
        interval_ceiling: 100
        backoff_millis: 2000
      - url: https://testnet-rpc.monad.xyz
        for: fallback
        initial_block_interval: 100
        interval_ceiling: 100
        backoff_millis: 2000`
    : chainId === 10143
    ? `    hypersync_config:
      url: https://10143.hypersync.xyz
    rpc:
      - url: https://testnet-rpc.monad.xyz
        for: fallback`
    : `    rpc:
      - url: http://127.0.0.1:8545
        for: sync`;

const yaml = `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# Generated by scripts/config.mjs from contracts/deployments/${chainId}.json. Do not edit by hand.
name: plenum-indexer
description: Plenum activity, manager actions, approvals, refusals, NAV and consent on Monad testnet
schema: ./schema.graphql
handlers: ./src/handlers
field_selection:
  transaction_fields:
    - hash

contracts:
  - name: PlenumFactory
    abi_file_path: ${abi("PlenumFactory")}
    events:
      - event: PlenumCreated
  - name: Plenum
    abi_file_path: ${abi("Plenum")}
    events:
      - event: MemberJoined
      - event: Contributed
      - event: Redeemed
      - event: ComplianceRefused
      - event: ActionExecuted
  - name: ManagerGateway
    abi_file_path: ${abi("ManagerGateway")}
    events:
      - event: ManagerAction
  - name: Governance
    abi_file_path: ${abi("Governance")}
    events:
      - event: Escalated
      - event: Approved
      - event: ProposalExecuted
      - event: Paused
      - event: Unpaused
      - event: ManagerReplaced
  - name: NavOracle
    abi_file_path: ${abi("NavOracle")}
    events:
      - event: NavReported
  - name: ConsentRegistry
    abi_file_path: ${abi("ConsentRegistry")}
    events:
      - event: ConsentGranted
      - event: ConsentRevoked

chains:
  - id: ${chainId}
    start_block: ${d.startBlock}
${chainSource}
    contracts:
      - name: PlenumFactory
        address: "${d.factory}"
      - name: NavOracle
        address: "${d.navOracle}"
      - name: ConsentRegistry
        address: "${d.consentRegistry}"
      # Plenum, ManagerGateway and Governance are per-group clones registered from PlenumCreated.
      - name: Plenum
      - name: ManagerGateway
      - name: Governance
`;
writeFileSync(join(import.meta.dirname, "../config.yaml"), yaml);
console.log(`config.yaml written for chain ${chainId}${rpcOnly ? " (RPC-only)" : ""}`);
